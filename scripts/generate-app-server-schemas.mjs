import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryDirectory = dirname(scriptDirectory);
const schemaDirectory = join(
  repositoryDirectory,
  'packages',
  'adapter-codex-app-server',
  'schemas',
);
const generatedPath = join(
  repositoryDirectory,
  'packages',
  'adapter-codex-app-server',
  'src',
  'generated-schemas.ts',
);
const expectedJsonSchema = 'https://json-schema.org/draft/2020-12/schema';

function fail(message) {
  throw new Error(`Invalid Codex app-server schema artifact: ${message}`);
}

function versionFromFilename(name) {
  const match = /^(\d+\.\d+\.\d+)\.json$/u.exec(name);
  if (!match) return undefined;
  return match[1];
}

function assertArtifact(value, version, filename) {
  if (!value || typeof value !== 'object' || Array.isArray(value))
    fail(`${filename} must contain a JSON object.`);
  if (value.$schema !== expectedJsonSchema)
    fail(`${filename} must declare the draft 2020-12 JSON Schema.`);
  if (
    value.$id !==
    `https://vibetrace.dev/schemas/codex-app-server/${version}.json`
  )
    fail(`${filename} has an unexpected $id.`);
  if (value.title !== `Codex app-server ${version} JSON-RPC envelope`)
    fail(`${filename} has an unexpected title.`);
  if (value.type !== 'object' || value.additionalProperties !== true)
    fail(`${filename} must be an extensible object envelope.`);
  const properties = value.properties;
  if (
    !properties ||
    typeof properties !== 'object' ||
    Array.isArray(properties)
  )
    fail(`${filename} must define envelope properties.`);
  const keys = Object.keys(properties).sort().join(',');
  if (keys !== 'error,id,method,params,result')
    fail(`${filename} has unexpected envelope properties: ${keys}.`);
  if (
    JSON.stringify(properties.id?.type) !==
    JSON.stringify(['string', 'integer'])
  )
    fail(`${filename} id must accept string or integer JSON-RPC IDs.`);
  if (
    properties.method?.type !== 'string' ||
    properties.method?.minLength !== 1
  )
    fail(`${filename} method must be a non-empty string.`);
  if (
    properties.params?.type !== 'object' ||
    properties.params?.additionalProperties !== true ||
    properties.error?.type !== 'object' ||
    properties.error?.additionalProperties !== true
  )
    fail(`${filename} params and error must preserve extensible objects.`);
  if (!properties.result || typeof properties.result !== 'object')
    fail(`${filename} result must allow any JSON value.`);
}

async function loadArtifacts() {
  const names = (await readdir(schemaDirectory))
    .filter((name) => name.endsWith('.json'))
    .sort((left, right) => left.localeCompare(right));
  if (names.length === 0) fail('no JSON artifacts found.');
  const artifacts = [];
  for (const filename of names) {
    const version = versionFromFilename(filename);
    if (!version) fail(`${filename} is not a stable version artifact.`);
    const value = JSON.parse(
      await readFile(join(schemaDirectory, filename), 'utf8'),
    );
    assertArtifact(value, version, filename);
    artifacts.push({ version, value });
  }
  return artifacts;
}

function generatedSource(artifacts) {
  const entries = artifacts
    .map(
      ({ version, value }) =>
        `  ${JSON.stringify(version)}: ${JSON.stringify(value, null, 2).replaceAll('\n', '\n  ')},`,
    )
    .join('\n');
  return `/** Generated by scripts/generate-app-server-schemas.mjs. Do not edit. */\n\nexport const CODEX_APP_SERVER_VALIDATED_VERSIONS = ${JSON.stringify(artifacts.map(({ version }) => version))} as const;\n\nexport const APP_SERVER_SCHEMA_ARTIFACTS = {\n${entries}\n} as const;\n\nexport type AppServerSchemaArtifact = (typeof APP_SERVER_SCHEMA_ARTIFACTS)[keyof typeof APP_SERVER_SCHEMA_ARTIFACTS];\n`;
}

const artifacts = await loadArtifacts();
const expected = await prettier.format(generatedSource(artifacts), {
  filepath: generatedPath,
  parser: 'typescript',
  singleQuote: true,
  trailingComma: 'all',
});
const check = process.argv.includes('--check');
let actual;
try {
  actual = await readFile(generatedPath, 'utf8');
} catch (error) {
  if (!check && error?.code === 'ENOENT') actual = undefined;
  else throw error;
}
if (check) {
  if (actual !== expected)
    throw new Error(
      `${generatedPath} is stale; run pnpm schema:generate and commit the generated artifact.`,
    );
} else if (actual !== expected) {
  await writeFile(generatedPath, expected, 'utf8');
}
